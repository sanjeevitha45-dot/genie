// Reference date aligned with workspace context (2026-11-18)
export const REFERENCE_TODAY = '2026-11-18';

export function daysUntilDate(isoDate?: string): number | null {
  if (!isoDate) return null;
  const base = new Date(`${REFERENCE_TODAY}T00:00:00Z`).getTime();
  const target = new Date(`${isoDate}T00:00:00Z`).getTime();
  return Math.round((target - base) / (1000 * 60 * 60 * 24));
}

export function computeStockHealth(item: InventoryItem): StockHealth {
  if (item.onHand <= 0 || item.onHand <= item.reorderPoint * 0.45) {
    return 'critical';
  }
  const expDays = daysUntilDate(item.expiryDate);
  if (expDays !== null && expDays <= 5) {
    return 'expiring';
  }
  if (item.onHand <= item.reorderPoint) {
    return 'low';
  }
  return 'optimal';
}

